export function err(
  code: string,
  message: string,
  extra?: { path?: string; line?: number },
): ImportMessage {
  return { code, message, ...extra };
}

export function warn(
  code: string,
  message: string,
  extra?: { path?: string; line?: number },
): ImportMessage {
  return { code, message, ...extra };
}

export function hasErrors(result: { errors: ImportMessage[] }): boolean {
  return result.errors.length > 0;
}

